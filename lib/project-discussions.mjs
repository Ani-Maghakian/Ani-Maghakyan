export function escapeHtml(value) {
  return String(value).replaceAll('&', '&amp;').replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;').replaceAll('"', '&quot;').replaceAll("'", '&#39;');
}

export function validateConfig(config) {
  if (!config || typeof config.enabled !== 'boolean') throw new Error('Set an explicit enabled boolean.');
  if (config.provider !== 'github-issues' || config.repository !== 'Ani-Maghakian/Ani-Maghakyan') {
    throw new Error('Only the approved public GitHub repository is supported.');
  }
  if (config.contactEmail !== 'maghaqyan@gmail.com') throw new Error('Use the owner-approved address.');
  if ('endpoint' in config) throw new Error('No external backend endpoint is used.');
  return config;
}

export function pageIdentity(relativeFile) {
  const parts = relativeFile.replaceAll('\\', '/').split('/');
  const locale = ['en', 'ru'].includes(parts[0]) ? parts.shift() : 'hy';
  const tail = parts.join('/').replace(/(^|\/)index\.html$/, '').replace(/\/$/, '');
  const match = /^projects\/([a-z0-9]+(?:-[a-z0-9]+)*)$/.exec(tail);
  return { locale, tail, project: match ? match[1] : null };
}

export function mailto(locale, context = '') {
  const text = discussionCopy[locale] || discussionCopy.hy;
  const subject = text.subject + (context ? ` — ${context}` : '');
  return `mailto:maghaqyan@gmail.com?subject=${encodeURIComponent(subject)}`;
}

function contactFragment(locale, context) {
  const t = discussionCopy[locale];
  return `<aside class="discussion-business" data-discussion-contact>
  <a class="discussion-business-action" data-track="contact_email" href="${escapeHtml(mailto(locale, context))}">${escapeHtml(t.business)}</a>
  <div class="discussion-email"><a href="mailto:maghaqyan@gmail.com">maghaqyan@gmail.com</a>
  <button type="button" data-copy-email>${escapeHtml(t.copy)}</button></div>
  <p data-copy-status role="status" aria-live="polite"></p>
</aside>`;
}

export function discussionFragment(project, locale, config, opinions = []) {
  const t = discussionCopy[locale];
  const records = opinions.filter((item) => item.project === project);
  const labels = Object.entries(t).map(([key, value]) => `data-text-${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}="${escapeHtml(value)}"`).join(' ');
  function card(item, nested = false) {
    const reply = nested ? '' : `<button type="button" data-opinion-reply="${item.id}" data-reply-name="${escapeHtml(item.name)}">${escapeHtml(t.reply)}</button>`;
    const children = records.filter((record) => record.parent === item.id);
    return `<article class="discussion-comment" id="opinion-${item.id}" lang="${item.locale}"><header><strong>${escapeHtml(item.name)}</strong><time datetime="${item.createdAt}">${item.createdAt.slice(0, 10)}</time><a href="${escapeHtml(item.source)}" target="_blank" rel="noopener noreferrer">GitHub</a></header><p>${escapeHtml(item.body)}</p>${reply}${children.length ? `<div class="discussion-replies">${children.map((child) => card(child, true)).join('')}</div>` : ''}</article>`;
  }
  return `<section id="discussion" class="project-discussion" tabindex="-1" aria-labelledby="discussion-title"
 data-project-discussion data-project="${escapeHtml(project)}" data-locale="${locale}" data-repository="${config.repository}" ${labels}>
<h2 id="discussion-title">${escapeHtml(t.heading)}</h2><p>${escapeHtml(t.intro)}</p>
<p class="discussion-notice">${escapeHtml(t.notice)}</p>
<details class="discussion-privacy"><summary>${escapeHtml(t.privacy)}</summary><p>${escapeHtml(t.privacyText)} <a href="mailto:maghaqyan@gmail.com">maghaqyan@gmail.com</a></p></details>
<div data-discussion-list>${records.length ? records.filter((item) => !item.parent).map((item) => card(item)).join('') : `<p>${escapeHtml(t.empty)}</p>`}</div>
${config.enabled ? `<noscript><p>${escapeHtml(t.nojs)}</p></noscript>
<form data-discussion-form hidden>
<p data-reply-context hidden></p><button type="button" data-cancel-reply hidden>${escapeHtml(t.cancel)}</button>
<label for="discussion-name">${escapeHtml(t.name)}</label><input id="discussion-name" name="author" type="text" minlength="2" maxlength="60" required autocomplete="nickname">
<label for="discussion-body">${escapeHtml(t.body)}</label><textarea id="discussion-body" name="body" minlength="5" maxlength="3000" rows="5" required></textarea>
<label class="discussion-consent"><input name="consent" type="checkbox" required><span>${escapeHtml(t.consent)}</span></label>
<button type="submit">${escapeHtml(t.prepare)}</button><p data-discussion-send-status role="status" aria-live="polite"></p>
<div data-handoff hidden><p data-handoff-instructions></p>
<div data-long-draft hidden><label for="discussion-copy-draft">${escapeHtml(t.draftLabel)}</label><textarea id="discussion-copy-draft" readonly rows="6"></textarea><button type="button" data-copy-draft>${escapeHtml(t.copyDraft)}</button></div>
<a class="discussion-business-action" data-github-handoff target="_blank" rel="noopener noreferrer">${escapeHtml(t.continue)}</a>
</div></form>` : `<p>${escapeHtml(t.disabled)}</p>`}
</section>`;
}

/** Only the known generated anchor shapes are changed; scripts stay byte-identical. */
export function integrateHtml(html, relativeFile, config, assetSuffix = '', opinions = []) {
  validateConfig(config);
  if (html.includes('<!-- PROJECT_DISCUSSIONS_GITHUB_V2 -->')) return html;
  const canonical = /<link\b[^>]*rel="canonical"[^>]*href="([^"]+)"[^>]*>/i.exec(html)?.[1];
  if (!canonical || !html.includes('</main>')) return html;
  const { locale, project, tail } = pageIdentity(relativeFile);
  const t = discussionCopy[locale];
  const pageUrl = new URL(canonical);
  const rootPath = pageUrl.pathname.slice(0, pageUrl.pathname.length -
    ((locale === 'hy' ? '' : locale + '/') + (tail ? tail + '/' : '')).length);
  if (!rootPath.endsWith('/')) throw new Error(`Cannot derive site asset root: ${canonical}`);
  const title = /<h1\b[^>]*>([\s\S]*?)<\/h1>/i.exec(html)?.[1].replace(/<[^>]*>/g, '').trim() || '';
  const businessContext = project || tail.startsWith('services/') ? title : '';
  const emailHref = mailto(locale, businessContext);
  const oldLabels = new Set(['Քննարկել նախագիծը', 'Discuss a project', 'Обсудить проект']);
  // Preserve external sources, viewing URLs, social profile links and language/navigation URLs.
  html = html.split(/(<script\b[\s\S]*?<\/script>)/gi).map((part) => {
    if (/^<script\b/i.test(part)) return part;
    return part.replace(/<a\b([^>]*)>([\s\S]*?)<\/a>/gi, (full, attributes, contents) => {
      const label = contents.replace(/<[^>]*>/g, '').trim();
      const business = /data-track="contact_(instagram|email)"/.test(attributes);
      if (!business && !oldLabels.has(label)) return full;
      const discuss = !business && Boolean(project);
      let attrs = attributes.replace(/\s(?:href|target|rel|data-track)="[^"]*"/g, '');
      const href = discuss ? '#discussion' : emailHref;
      attrs += ` href="${escapeHtml(href)}" data-track="${discuss ? 'view_discussion' : 'contact_email'}"`;
      return `<a${attrs}>${escapeHtml(discuss ? t.discuss : t.business)}</a>`;
    });
  }).join('');
  if (!project) {
    html = html.replace(/(<a\b[^>]*class="(?:project-title-link|featured-poster-link(?: featured-text-cover)?)"[^>]*>[\s\S]*?<\/a>)/g, (full) => {
      if (!full.includes('class="project-title-link"')) return full;
      const href = /href="([^"]*\/projects\/[a-z0-9-]+\/)"/.exec(full)?.[1];
      return href ? `${full} <a class="project-discuss-link" href="${href}#discussion" data-track="view_discussion">${escapeHtml(t.discuss)}</a>` : full;
    });
  }
  const block = '\n<!-- PROJECT_DISCUSSIONS_GITHUB_V2 -->\n' +
    (project ? discussionFragment(project, locale, config, opinions) : '') + contactFragment(locale, businessContext) + '\n';
  html = html.replace('</main>', block + '</main>');
  html = html.replace('</head>', `<link rel="stylesheet" href="${rootPath}project-discussions.css${assetSuffix}">\n<script src="${rootPath}project-discussions.js${assetSuffix}" type="module"></script>\n</head>`);
  return html;
}
